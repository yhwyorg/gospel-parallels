// Gospel names arrive in the nominative ("Марк"), but almost every phrase they sit
// in ("Евангелие от Марка", "у Марка", "нет ни у Марка, ни у Иоанна") needs the
// genitive. Keyed by the translated name so it works on the strings the views pass.
const GENITIVE: Record<Gospel, string> = { matthew: 'Матфея', mark: 'Марка', luke: 'Луки', john: 'Иоанна' };
const genOf = Object.fromEntries(GOSPELS.map((g) => [BOOKS.ru.names[g], GENITIVE[g]]));
const gen = (name: string) => genOf[name] ?? name;

/** Russian plural: 1 раздел, 2 раздела, 5 разделов, 21 раздел, 11 разделов. */
function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
